/**
 * Given a category, returns N unique random topics from the list.
 */
export function getRandomAutopilotTopics(category: "travel" | "life_info" | "food" | "trend", count: number = 1): string[] {
  const pool = AUTOPILOT_TOPICS[category] || AUTOPILOT_TOPICS.food;
  
  // Create a copy to shuffle
  const shuffled = [...pool].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
